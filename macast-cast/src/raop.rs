//! AirPlay audio (RAOP): the config we hand to `shairport-sync`.
//!
//! Rust counterpart of `macast/plugins/protocol/raop.py`'s decision layer (`:72-122`).
//! Macast does not implement AirPlay audio itself — it supervises `shairport-sync` — so the
//! portable part is smaller than it looks: **who the device is called, and the file that says
//! so**.
//!
//! ## The escaping is the feature
//!
//! This config is C-style: `name = "…";`. An unescaped `"` in the device name ends the string
//! early and turns the rest of the user's chosen name into a syntax error, and
//! `shairport-sync` **refuses to start** on one. The failure the user sees is therefore "AirPlay
//! audio stopped working after I renamed my Mac", with nothing pointing at the name they typed.
//! So the backslash is escaped before the quote (order matters — quoting first would
//! double-escape), and a name that would be ambiguous at all falls back to `Macast`.
//!
//! ## The name has three sources, in order
//!
//! 1. the plugin's own `RAOP_Device_Name` override, when the user set one;
//! 2. Macast's DLNA friendly name;
//! 3. the literal `Macast`.
//!
//! The `has`-before-`get` in the reference is not style: `Setting.get` with a default
//! **creates** the key (AGENTS.md §4.2's first trap), so reading the override with a default
//! would write it to the user's settings file on every start. This module takes the value as an
//! input for exactly that reason — the caller decides whether the key exists.

/// The file name inside the settings directory.
pub const CONFIG_NAME: &str = "shairport-sync.conf";

/// Where a GUI-launched app may find the binary when `PATH` is empty.
///
/// A Dock-launched app does not inherit the shell's `PATH`, so a Homebrew or MacPorts install
/// would look missing otherwise — the same rule as every other supervised binary in this
/// repository.
pub const EXTRA_BIN_DIRS: &[&str] = &[
    "/opt/homebrew/bin",
    "/usr/local/bin",
    "/opt/local/bin",
    "/usr/bin",
];

/// The program being supervised.
pub const PROGRAM: &str = "shairport-sync";

/// The settings key for the name override.
pub const KEY_DEVICE_NAME: &str = "RAOP_Device_Name";

/// Which name to advertise.
///
/// `override` is `None` when the key is absent, and `Some("")` when it exists but is blank —
/// both mean "follow the friendly name". Collapsing the two would be wrong in the other
/// direction: an empty override is a real value the user may have left behind, and it is not a
/// reason to advertise nothing.
pub fn device_name(override_name: Option<&str>, friendly_name: &str) -> String {
    if let Some(name) = override_name {
        let trimmed = name.trim();
        if !trimmed.is_empty() {
            return trimmed.to_string();
        }
    }
    let friendly = friendly_name.trim();
    if friendly.is_empty() {
        "Macast".to_string()
    } else {
        friendly.to_string()
    }
}

/// Escape a name for the C-style string literal.
///
/// **The backslash goes first.** Doing it the other way round would turn `"` into `\"` and then
/// escape that backslash again, producing `\\"` — which terminates the string one character
/// earlier than intended.
pub fn escape(name: &str) -> String {
    name.replace('\\', "\\\\").replace('"', "\\\"")
}

/// The generated config, as text.
///
/// The header comments are the reference's, and they are load-bearing: they are the only place
/// a user who opens this file learns that it is generated and will be overwritten.
pub fn config_body(name: &str) -> String {
    // Only `is_empty` falls back, **not** `trim().is_empty()`: the reference's guard is
    // `(name or 'Macast')`, so a whitespace-only name is written out verbatim. That looks like
    // an oversight, and it is — but the fallback for a blank name already happened upstream in
    // `device_name`, so a blank string reaching here is a caller bug, not a name to invent.
    // Matching the reference keeps this function about escaping only.
    let chosen = if name.is_empty() { "Macast" } else { name };
    let safe = escape(chosen);
    format!(
        "// Generated by Macast's \"AirPlay Audio (RAOP)\" plugin.\n\
         // The service name comes from Macast's friendly-name setting; edit it\n\
         // there rather than here, or the next start will overwrite this file.\n\
         general =\n\
         {{\n\
         \x20   name = \"{safe}\";\n\
         }};\n"
    )
}

/// Find the binary: `PATH` first, then the install directories.
///
/// Both lookups are caller-supplied so the answer does not depend on what this machine has
/// installed. Checked at start, never at import — installing `shairport-sync` while Macast runs
/// must not need a restart.
pub fn find_binary(
    which: impl Fn(&str) -> Option<String>,
    is_executable: impl Fn(&str) -> bool,
) -> Option<String> {
    if let Some(found) = which(PROGRAM) {
        return Some(found);
    }
    for directory in EXTRA_BIN_DIRS {
        let candidate = format!("{directory}/{PROGRAM}");
        if is_executable(&candidate) {
            return Some(candidate);
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    // `pin_test_dir()` first in every test, like the rest of this crate: this module decides a
    // config path inside the settings directory, so a test that ever writes would otherwise
    // land in the user's real one (AGENTS.md §12.2).

    #[test]
    fn the_backslash_is_escaped_before_the_quote() {
        crate::pin_test_dir();
        // Order is the whole test. Quote-first produces `\\"` for an input of `\"`, which ends
        // the string one character early.
        assert_eq!(escape(r#"a"b"#), r#"a\"b"#);
        assert_eq!(escape(r"a\b"), r"a\\b");
        assert_eq!(escape(r#"a\"b"#), r#"a\\\"b"#);
    }

    #[test]
    fn a_quote_in_the_name_cannot_end_the_string_early() {
        crate::pin_test_dir();
        // The defect this exists for: `name = "My "Mac"";` is a syntax error, and
        // shairport-sync refuses to start — so AirPlay audio silently stops working after a
        // rename, with nothing pointing at the name.
        let body = config_body(r#"My "Mac"#);
        let name_line = body
            .lines()
            .find(|line| line.trim_start().starts_with("name = "))
            .expect("the config has a name line");
        // Exactly two unescaped quotes on that line: the delimiters.
        let unescaped = name_line
            .char_indices()
            .filter(|(index, ch)| {
                *ch == '"' && (*index == 0 || &name_line[index - 1..*index] != "\\")
            })
            .count();
        assert_eq!(
            unescaped, 2,
            "the name line must contain only its two delimiters: {name_line}"
        );
        assert!(body.contains(r#"name = "My \"Mac";"#), "{body}");
    }

    #[test]
    fn the_name_comes_from_the_override_then_the_friendly_name_then_the_literal() {
        crate::pin_test_dir();
        assert_eq!(device_name(Some("Kitchen"), "Study"), "Kitchen");
        // An empty or whitespace override is not a name, and it must not advertise nothing.
        assert_eq!(device_name(Some("   "), "Study"), "Study");
        assert_eq!(device_name(Some(""), "Study"), "Study");
        assert_eq!(device_name(None, "Study"), "Study");
        // Both blank: the reference's literal, so shairport-sync never gets an empty name.
        assert_eq!(device_name(None, ""), "Macast");
        assert_eq!(device_name(None, "  "), "Macast");
        assert_eq!(device_name(Some(""), ""), "Macast");
    }

    #[test]
    fn the_override_is_trimmed_because_a_trailing_space_is_invisible_to_the_user() {
        crate::pin_test_dir();
        // `"Kitchen "` and `"Kitchen"` look identical in every AirPlay list, so a stray space
        // reads as a duplicate device.
        assert_eq!(device_name(Some("  Kitchen  "), "Study"), "Kitchen");
    }

    #[test]
    fn the_config_carries_the_warning_that_it_is_generated() {
        crate::pin_test_dir();
        // The only place a user who opens the file learns it will be overwritten.
        let body = config_body("Kitchen");
        assert!(body.contains("Generated by Macast"));
        assert!(body.contains("will overwrite this file"));
        assert!(body.contains(r#"name = "Kitchen";"#));
        // A blank name must still produce a valid file rather than `name = "";`.
        assert!(config_body("").contains(r#"name = "Macast";"#));
    }

    /// Every name and config the reference produced, replayed against this port.
    ///
    /// Produced by executing the reference's `config_body` over twelve names: the ordinary
    /// case, blank, whitespace-only, and six shapes of quote/backslash that a user can type.
    /// The `"  "` row is the surprising one — the reference writes the spaces through, because
    /// its fallback is `(name or 'Macast')` and `"  "` is truthy.
    #[test]
    fn every_reference_config_replays_byte_for_byte() {
        crate::pin_test_dir();
        let corpus = include_str!("../tests/golden/raop_config.jsonl");
        let mut rows = 0usize;
        for line in corpus.lines().filter(|line| !line.trim().is_empty()) {
            let row: serde_json::Value = serde_json::from_str(line).expect("corpus row");
            let name = row["name"].as_str().expect("name");
            let expected = row["config"].as_str().expect("config");
            assert_eq!(
                config_body(name), expected,
                "config_body({name:?}) disagrees with the reference"
            );
            rows += 1;
        }
        assert_eq!(rows, 12, "the corpus lost rows");
    }

    #[test]
    fn the_binary_is_looked_for_on_path_before_the_install_directories() {
        crate::pin_test_dir();
        let found = find_binary(
            |name| (name == "shairport-sync").then(|| "/opt/homebrew/bin/shairport-sync".into()),
            |_| true,
        );
        assert_eq!(found.as_deref(), Some("/opt/homebrew/bin/shairport-sync"));

        // A GUI-launched app has no shell PATH, so the fallback is what makes it work at all.
        let found = find_binary(
            |_| None,
            |path| path == "/usr/local/bin/shairport-sync",
        );
        assert_eq!(found.as_deref(), Some("/usr/local/bin/shairport-sync"));

        assert_eq!(find_binary(|_| None, |_| false), None);
    }

    #[test]
    fn the_install_directories_are_the_ones_the_rest_of_the_repo_uses() {
        crate::pin_test_dir();
        // Three package managers plus the system path: Homebrew on both architectures,
        // MacPorts, and the plain `/usr/bin` a Linux install lands in.
        assert_eq!(EXTRA_BIN_DIRS.len(), 4);
        assert!(EXTRA_BIN_DIRS.contains(&"/opt/homebrew/bin"));
        assert!(EXTRA_BIN_DIRS.contains(&"/usr/local/bin"));
        assert!(EXTRA_BIN_DIRS.contains(&"/opt/local/bin"));
        assert!(EXTRA_BIN_DIRS.contains(&"/usr/bin"));
        assert_eq!(CONFIG_NAME, "shairport-sync.conf");
        assert_eq!(KEY_DEVICE_NAME, "RAOP_Device_Name");
    }
}
