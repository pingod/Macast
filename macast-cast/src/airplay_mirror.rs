//! AirPlay screen mirror: the option file we hand to `uxplay`.
//!
//! Rust counterpart of `macast/plugins/protocol/airplay_mirror.py`'s decision layer
//! (`:258-330`). Macast supervises `uxplay`; what is portable is **the name**, **the user's
//! extra options**, and **the file both travel in**.
//!
//! ## `-rc <file>`, never `$UXPLAYRC`
//!
//! The reference's comment gives the reason and it is worth repeating: when `$UXPLAYRC` points
//! at a file that does not exist, uxplay **silently falls back to `~/.uxplayrc`** — so it can
//! read, and be induced to write, a file in the user's home directory. `-rc` on a missing file
//! exits with an error instead. Wrong-and-loud beats wrong-and-silent when the thing being
//! guessed is which config to read.
//!
//! ## Three quoting consequences, all from uxplay's parser
//!
//! uxplay splits a line on spaces, honours `"..."` as one item, and gives the first item a
//! leading `-`. Therefore:
//!
//! * the value **must be quoted** — a friendly name with a space is the normal case;
//! * a quote or backslash inside the value **cannot be escaped** (the backslash survives into
//!   the token, and a quote would end the item early) so they become **spaces**;
//! * a value starting with `-` reads as "this option had no argument", and uxplay **refuses to
//!   start** — so leading dashes are dropped.
//!
//! ## The user's options go last
//!
//! uxplay runs the file through the same parser as the command line and **last occurrence
//! wins**. Our two defaults therefore come first, and the user's lines are appended, so an
//! advanced-setting option overrides a default instead of fighting with it. That ordering is
//! the whole reason a hand-picked toggle list was rejected in favour of the option language.

/// The file name inside the settings directory.
pub const RC_NAME: &str = "uxplay.rc";

/// The advanced-settings key holding the user's extra options.
pub const OPTIONS_KEY: &str = "Mirror_Uxplay_Options";

/// The program being supervised.
pub const PROGRAM: &str = "uxplay";

/// Make a name safe for the option file.
///
/// `safe_name` in the reference; see the module docs for why each of the three steps exists.
pub fn safe_name(name: &str) -> String {
    let base = if name.trim().is_empty() { "Macast" } else { name };
    // Replace, never escape: escapes do not survive uxplay's tokenizer.
    let mut cleaned: String = base
        .chars()
        .map(|ch| match ch {
            '"' | '\\' | '\'' | '\r' | '\n' | '\t' => ' ',
            other => other,
        })
        .collect();
    // Collapse runs of whitespace, then drop leading dashes (a value starting with `-` is read
    // as a missing argument and makes uxplay refuse to start), then trim again.
    cleaned = cleaned.split_whitespace().collect::<Vec<_>>().join(" ");
    cleaned = cleaned.trim_start_matches('-').trim().to_string();
    if cleaned.is_empty() {
        "Macast".to_string()
    } else {
        cleaned
    }
}

/// The user's extra options, one per line, with the leading dash removed.
///
/// Accepting `-pin 1234` as well as `pin 1234` is deliberate: the file format wants no dash,
/// but every other tool takes one, so people type it.
pub fn extra_rc_lines(raw: &str) -> Vec<String> {
    raw.lines()
        .map(|line| line.trim())
        .filter(|line| !line.is_empty())
        .map(|line| match line.strip_prefix('-') {
            Some(rest) => rest.trim().to_string(),
            None => line.to_string(),
        })
        .collect()
}

/// The generated option file, as text.
///
/// `platform` is an input, not `std::env::consts::OS`: the macOS line exists because the
/// official GStreamer build only offers `glimagesink` and `osxvideosink`, and the reference
/// picks the latter rather than letting `autovideosink` choose. A Linux runner asking about
/// `darwin` must get `darwin`'s file.
pub fn rc_body(name: &str, extra_lines: &[String], platform: &str) -> String {
    let mut lines = vec![
        "# Generated by Macast's \"AirPlay Screen Mirror\" plugin.".to_string(),
        "# The server name comes from Macast's friendly-name setting; edit it".to_string(),
        "# there rather than here, or the next start will overwrite this file.".to_string(),
        format!(
            "# Extra options: advanced setting {OPTIONS_KEY} (one uxplay option per line, no leading dash)."
        ),
        format!("n \"{}\"", safe_name(name)),
        // Upstream's own recommendation: with timestamp sync (the default since uxplay 1.64)
        // many frames are dropped on macOS, and a screen mirror has no audio to sync against.
        "vsync no".to_string(),
    ];
    if platform == "darwin" {
        lines.push("vs osxvideosink".to_string());
    }
    lines.extend(extra_lines.iter().cloned());
    let mut text = lines.join("\n");
    text.push('\n');
    text
}

/// The argv that starts uxplay.
///
/// Exactly two elements: the binary and `-rc <file>`. **No `-p`**: that option pins the legacy
/// ports 7100/7000/7001, and 7000 is both this app's own AirPlay port and the system receiver's
/// — the reference says so in its own header. Without `-p`, uxplay picks a dynamic port and
/// advertises it over mDNS, which is strictly better.
pub fn argv(binary: &str, rc_path: &str) -> Vec<String> {
    vec![
        binary.to_string(),
        "-rc".to_string(),
        rc_path.to_string(),
    ]
}

/// What is wrong with the argv, if anything. A guard for the rule above.
pub fn argv_problems(argv: &[String]) -> Vec<String> {
    let mut problems = Vec::new();
    if argv.len() != 3 || argv[1] != "-rc" {
        problems.push("uxplay must be started as `<binary> -rc <file>`".to_string());
    }
    if argv.iter().any(|arg| arg == "-p") {
        problems.push(
            "`-p` pins the legacy ports 7100/7000/7001, and 7000 is our own AirPlay port"
                .to_string(),
        );
    }
    problems
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_quote_or_backslash_becomes_a_space_because_it_cannot_be_escaped() {
        crate::pin_test_dir();
        // Escapes do not survive uxplay's tokenizer: a backslash stays in the token and a quote
        // ends the item early. So the only safe replacement is a space.
        assert_eq!(safe_name(r#"My "Mac""#), "My Mac");
        assert_eq!(safe_name(r"a\b"), "a b");
        assert_eq!(safe_name("a'b"), "a b");
        // Newlines and tabs would break the line-oriented file entirely.
        assert_eq!(safe_name("a\r\nb"), "a b");
        assert_eq!(safe_name("a\tb"), "a b");
    }

    #[test]
    fn a_leading_dash_is_dropped_because_uxplay_reads_it_as_a_missing_argument() {
        crate::pin_test_dir();
        // The failure is not cosmetic: uxplay refuses to start, so the viewer sees "mirroring
        // is broken" after renaming their Mac to something starting with a dash.
        assert_eq!(safe_name("-Kitchen"), "Kitchen");
        assert_eq!(safe_name("--Kitchen"), "Kitchen");
        assert_eq!(safe_name("- Kitchen"), "Kitchen");
    }

    #[test]
    fn a_name_that_cleans_to_nothing_falls_back_rather_than_leaving_an_empty_value() {
        crate::pin_test_dir();
        // `n ""` would be an option with no argument.
        assert_eq!(safe_name(""), "Macast");
        assert_eq!(safe_name("   "), "Macast");
        assert_eq!(safe_name("\"\"\"\""), "Macast");
        assert_eq!(safe_name("---"), "Macast");
    }

    #[test]
    fn ordinary_names_survive_intact_including_spaces_and_non_ascii() {
        crate::pin_test_dir();
        // The common case must not be damaged by the sanitiser: a name with a space is normal.
        assert_eq!(safe_name("Pavia's MacBook Pro"), "Pavia s MacBook Pro");
        assert_eq!(safe_name("Kitchen Speaker"), "Kitchen Speaker");
        assert_eq!(safe_name("Pavia的MacBook Pro"), "Pavia的MacBook Pro");
        // Runs of whitespace collapse, so the option file cannot grow a double space either.
        assert_eq!(safe_name("a   b"), "a b");
    }

    #[test]
    fn the_user_may_type_the_dash_they_are_used_to() {
        crate::pin_test_dir();
        // The file format wants no dash, but every other tool takes one.
        assert_eq!(
            extra_rc_lines("-pin 1234\nvs 0\n\n  -restrict  "),
            vec!["pin 1234".to_string(), "vs 0".to_string(), "restrict".to_string()]
        );
        assert!(extra_rc_lines("").is_empty());
        assert!(extra_rc_lines("   \n\n  ").is_empty());
    }

    #[test]
    fn the_users_options_come_last_so_they_override_our_defaults() {
        crate::pin_test_dir();
        // uxplay's parser is last-wins, so ordering is the whole mechanism by which the
        // advanced setting can override `vsync no`.
        let extra = vec!["vsync yes".to_string()];
        let body = rc_body("Kitchen", &extra, "linux");
        let vsync_lines: Vec<&str> = body
            .lines()
            .filter(|line| line.starts_with("vsync"))
            .collect();
        assert_eq!(vsync_lines, vec!["vsync no", "vsync yes"]);
        // …and the user's line is last in the file, not just last of its kind.
        let meaningful: Vec<&str> = body
            .lines()
            .filter(|line| !line.trim().is_empty() && !line.starts_with('#'))
            .collect();
        assert_eq!(meaningful.last(), Some(&"vsync yes"));
    }

    #[test]
    fn the_videosink_line_exists_only_on_macos() {
        crate::pin_test_dir();
        // The official GStreamer build for macOS offers only glimagesink and osxvideosink, and
        // upstream points at the former's problems. The platform is an input so a Linux runner
        // can ask about darwin.
        assert!(rc_body("Kitchen", &[], "darwin").contains("vs osxvideosink"));
        assert!(!rc_body("Kitchen", &[], "linux").contains("vs osxvideosink"));
        assert!(!rc_body("Kitchen", &[], "win32").contains("vs osxvideosink"));
    }

    #[test]
    fn the_file_is_line_oriented_and_ends_with_one_newline() {
        crate::pin_test_dir();
        // A file without a trailing newline leaves the last option unterminated for a
        // line-oriented reader, which is how "my last option does nothing" happens.
        let body = rc_body("Kitchen", &["pin 1234".to_string()], "linux");
        assert!(body.ends_with('\n'));
        assert!(!body.ends_with("\n\n"));
        assert!(body.contains("n \"Kitchen\""));
        // The header names the setting, so a user who opens the file learns where to edit.
        assert!(body.contains(OPTIONS_KEY));
        assert!(body.contains("will overwrite this file"));
    }

    #[test]
    fn the_argv_is_the_binary_and_an_rc_file_and_never_a_pinned_port() {
        crate::pin_test_dir();
        let argv = argv("/usr/local/bin/uxplay", "/tmp/uxplay.rc");
        assert_eq!(
            argv,
            vec![
                "/usr/local/bin/uxplay".to_string(),
                "-rc".to_string(),
                "/tmp/uxplay.rc".to_string()
            ]
        );
        assert!(argv_problems(&argv).is_empty());
        assert_eq!(RC_NAME, "uxplay.rc");
        assert_eq!(PROGRAM, "uxplay");
    }

    /// Every name, option list and file the reference produced, replayed against this port.
    ///
    /// Produced by executing the reference's `safe_name` / `extra_rc_lines` / `rc_body` over
    /// sixteen names, five option texts and three platforms (with and without extras): 27 rows.
    /// The rows that matter are the ones a user can type by accident — `-Kitchen`, a quote, a
    /// tab — because those are the ones that stop uxplay starting.
    #[test]
    fn every_reference_option_file_replays_identically() {
        crate::pin_test_dir();
        let corpus = include_str!("../tests/golden/airplay_mirror.jsonl");
        let mut rows = 0usize;
        for line in corpus.lines().filter(|line| !line.trim().is_empty()) {
            let row: serde_json::Value = serde_json::from_str(line).expect("corpus row");
            match row["kind"].as_str().expect("kind") {
                "safe_name" => {
                    let name = row["name"].as_str().expect("name");
                    assert_eq!(
                        safe_name(name),
                        row["out"].as_str().unwrap_or(""),
                        "safe_name({name:?}) disagrees"
                    );
                }
                "extra" => {
                    let raw = row["raw"].as_str().expect("raw");
                    let expected: Vec<String> = row["out"]
                        .as_array()
                        .expect("out")
                        .iter()
                        .map(|v| v.as_str().unwrap_or("").to_string())
                        .collect();
                    assert_eq!(extra_rc_lines(raw), expected, "extra_rc_lines({raw:?}) disagrees");
                }
                "body" => {
                    let name = row["name"].as_str().expect("name");
                    let platform = row["platform"].as_str().expect("platform");
                    let extra: Vec<String> = row["extra"]
                        .as_array()
                        .expect("extra")
                        .iter()
                        .map(|v| v.as_str().unwrap_or("").to_string())
                        .collect();
                    assert_eq!(
                        rc_body(name, &extra, platform),
                        row["out"].as_str().unwrap_or(""),
                        "rc_body({name:?}, {extra:?}, {platform}) disagrees"
                    );
                }
                other => panic!("unknown corpus kind {other}"),
            }
            rows += 1;
        }
        assert_eq!(rows, 27, "the corpus lost rows");
    }

    #[test]
    fn the_argv_guard_catches_a_pinned_port_and_a_wrong_shape() {
        crate::pin_test_dir();
        // `-p` is the one flag that must never appear: 7000 is our own AirPlay port and the
        // system receiver's, so pinning it collides instead of helping.
        let pinned = vec![
            "/usr/local/bin/uxplay".to_string(),
            "-p".to_string(),
            "-rc".to_string(),
            "/tmp/x".to_string(),
        ];
        let problems = argv_problems(&pinned);
        assert!(problems.iter().any(|p| p.contains("7100/7000/7001")));

        let wrong = vec!["/usr/local/bin/uxplay".to_string(), "/tmp/x".to_string()];
        assert!(!argv_problems(&wrong).is_empty());

        // `$UXPLAYRC` must never be how the file is named — a missing file under that variable
        // silently falls back to `~/.uxplayrc`.
        let env_style = vec!["uxplay".to_string()];
        assert!(
            !env_style.iter().any(|arg| arg.contains("UXPLAYRC")),
            "the file is passed with `-rc`, not through the environment"
        );
        assert!(argv_problems(&env_style)
            .iter()
            .any(|p| p.contains("`<binary> -rc <file>`")));
    }
}
