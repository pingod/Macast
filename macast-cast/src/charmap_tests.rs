//! Differential truth for the codec-space layer, copied out of the Python
//! oracle's own answers: `/tmp/mr11_oracle.py` wrote `/tmp/mr11_truth.txt`, and
//! every expectation below is `json.dumps` of one of its rows, re-rendered as a
//! Rust literal. Nothing here was typed from memory and nothing here asks for
//! CPython at run time.
//!
//! The two shapes the seams cannot spell are stated rather than silently dropped:
//!
//! * `lab` records CPython's two refusals (`LookupError` for an unknown spelling,
//!   `ValueError` for a label holding a null character) as separate strings, while
//!   [`crate::charmap::resolve_codec`] answers `None` for both. The collapse is the
//!   point: `decode_body` only ever asks "is there a name here", and 236 of these
//!   rows -- every one of them an error row -- are where the two answers agree.
//! * `dec` is rendered in three states because the seam has three: `"null"` is
//!   "no decoder here", `"err"` is "this label is real and these bytes are not
//!   valid for it", anything else is the text. Reading the first as the second
//!   would push a declined codec toward utf-8, which is exactly what
//!   [`crate::charmap::decode_by_label`]'s docstring forbids.


#[allow(dead_code)]
fn esc(s: &str) -> String {
    let mut out = String::from("\"");
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[allow(dead_code)]
fn unhex(s: &str) -> Vec<u8> {
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).expect("valid hex"))
        .collect()
}

